import { t } from "i18next";
import { toast } from "sonner";

/**
 * Clipboard helpers hardened against ClickFix-style attacks.
 *
 * ClickFix relies on a page silently placing attacker-controlled text on the
 * clipboard and then tricking the user into pasting it into a terminal. These
 * helpers therefore:
 * - only write inside an explicit user gesture (callers use onClick);
 * - never read the clipboard and never paste or execute anything;
 * - only accept single-line text that passed a caller-provided allowlist;
 * - show the copied value so the user can spot clipboard poisoning.
 */

function hasControlChars(value: string): boolean {
  for (let i = 0; i < value.length; i++) {
    const code = value.charCodeAt(i);
    if (
      (code >= 0 && code <= 8) ||
      code === 11 ||
      code === 12 ||
      (code >= 14 && code <= 31) ||
      code === 127
    ) {
      return true;
    }
  }
  return false;
}

export type CopyTextOptions = {
  /** Maximum accepted length, defaults to 8192 characters. */
  maxLength?: number;
  /** Additional allowlist check for the value that is about to be copied. */
  validate?: (value: string) => boolean;
  /** Show the exact copied value in the success toast. */
  showValue?: boolean;
};

export function isSingleLineText(value: string, maxLength = 8192): boolean {
  return (
    typeof value === "string" &&
    value.length > 0 &&
    value.length <= maxLength &&
    !value.includes("\r") &&
    !value.includes("\n") &&
    !hasControlChars(value)
  );
}

export function isValidIPv4(value: string): boolean {
  const parts = value.trim().split(".");
  return (
    parts.length === 4 &&
    parts.every(
      (part) =>
        /^(0|[1-9]\d{0,2})$/.test(part) && Number(part) >= 0 && Number(part) <= 255,
    )
  );
}

export function isValidIPv6(value: string): boolean {
  const text = value.trim();
  return (
    text.length > 0 &&
    text.length <= 64 &&
    text.includes(":") &&
    /^[0-9a-fA-F:.%]+$/.test(text) &&
    !text.includes(":::")
  );
}

export function isSafeHttpUrl(value: string): boolean {
  try {
    const url = new URL(value);
    return (
      (url.protocol === "http:" || url.protocol === "https:") &&
      !url.username &&
      !url.password &&
      isSingleLineText(value, 2048)
    );
  } catch {
    return false;
  }
}

/**
 * Only the install commands generated by the panel are allowed on the
 * clipboard. Refusing anything else keeps a compromised data field from
 * turning the copy button into a command-delivery primitive.
 */
export function isSafeInstallCommand(value: string): boolean {
  return (
    isSingleLineText(value, 4096) &&
    /^(?:wget -qO- |zsh <\(curl -sL |powershell\.exe -NoProfile -ExecutionPolicy Bypass -Command )/.test(
      value,
    )
  );
}

async function legacyCopy(text: string): Promise<void> {
  const textarea = document.createElement("textarea");
  textarea.value = text;
  textarea.setAttribute("readonly", "");
  textarea.style.position = "fixed";
  textarea.style.top = "0";
  textarea.style.left = "-9999px";
  textarea.style.opacity = "0";
  document.body.appendChild(textarea);
  try {
    textarea.focus();
    textarea.select();
    textarea.setSelectionRange(0, text.length);
    if (!document.execCommand("copy")) {
      throw new Error("execCommand copy failed");
    }
  } finally {
    document.body.removeChild(textarea);
  }
}

export async function writeClipboardText(text: string): Promise<void> {
  if (!isSingleLineText(text)) {
    throw new Error("Refusing to write unsafe clipboard text");
  }

  // ClickFix payloads are delivered by a page-initiated write. Require the
  // write to happen during a real user gesture instead of page load/timers.
  if (navigator.userActivation && !navigator.userActivation.isActive) {
    throw new Error("Clipboard write requires an active user gesture");
  }

  if (window.isSecureContext && navigator.clipboard?.writeText) {
    try {
      await navigator.clipboard.writeText(text);
      return;
    } catch {
      // Permission denied or API unavailable: fall back to the legacy path.
      // Self-hosted Komari instances are commonly served over plain HTTP.
    }
  }

  await legacyCopy(text);
}

/**
 * Copy a value after validation. Must be called from a user gesture (onClick).
 * Returns true only when the clipboard write succeeded.
 */
export async function copyText(
  text: string,
  options: CopyTextOptions = {},
): Promise<boolean> {
  const value = (text ?? "").trim();
  const maxLength = options.maxLength ?? 8192;

  if (
    !isSingleLineText(value, maxLength) ||
    (options.validate && !options.validate(value))
  ) {
    toast.error(t("copy_blocked", "复制内容不安全，已阻止"));
    return false;
  }

  try {
    await writeClipboardText(value);
    toast.success(
      t("copy_success", "已复制到剪贴板"),
      options.showValue ? { description: value } : undefined,
    );
    return true;
  } catch (err) {
    console.error("Failed to copy text: ", err);
    toast.error(t("copy_failed", "复制失败，请检查浏览器权限或使用 HTTPS"));
    return false;
  }
}
